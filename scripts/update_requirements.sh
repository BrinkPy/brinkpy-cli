#!/usr/bin/env bash
#
# Regenerate requirements.txt, the pinned list of every package in the
# development environment.
#
# Usage:
#   scripts/update_requirements.sh [python]
#
# Builds a throwaway virtual environment with the given Python (default:
# python3), installs Brinkpy with its dev extras from pyproject.toml, and
# writes the exact installed versions to requirements.txt. Using a clean
# environment keeps unrelated packages and conda "@ file://" paths out of
# the file.
#
# Edit dependencies in pyproject.toml, never in requirements.txt.

set -euo pipefail

PYTHON="${1:-python3}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

"$PYTHON" -m venv "$TMP/venv"
"$TMP/venv/bin/python" -m pip install --quiet --upgrade pip
"$TMP/venv/bin/python" -m pip install --quiet -e "$ROOT[dev]"

PYVER="$("$TMP/venv/bin/python" -c 'import platform; print(platform.python_version())')"
{
  echo "# Pinned development environment for Brinkpy CLI."
  echo "# Generated by scripts/update_requirements.sh with Python $PYVER."
  echo "# Edit dependencies in pyproject.toml, then rerun the script."
  echo "#"
  echo "# Recreate the environment:"
  echo "#   python -m venv venv && source venv/bin/activate"
  echo "#   pip install -r requirements.txt"
  echo "#   pip install -e . --no-deps"
  "$TMP/venv/bin/python" -m pip freeze --exclude-editable
} > "$ROOT/requirements.txt"

echo "Wrote $ROOT/requirements.txt (Python $PYVER)"
